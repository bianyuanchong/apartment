-- Recreate apartment.apartment with BIGINT identity PK (existing UUID rows are dropped).
DROP TABLE IF EXISTS apartment.apartment;

CREATE TABLE apartment.apartment (
    apartment_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(255) NOT NULL,
    url                   TEXT NOT NULL,
    is_active             BOOLEAN NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    address               TEXT,
    zip                   VARCHAR(10),
    latitude              NUMERIC(9, 6),
    longitude             NUMERIC(9, 6),
    geocode_status        VARCHAR(64),
    geocoded_at           TIMESTAMPTZ,
    poi_radius_m          INTEGER,
    poi_score             NUMERIC(8, 2),
    poi_scores            JSONB,
    unit_count_on_market  INTEGER,
    CONSTRAINT apartment_name_unique UNIQUE (name)
);
